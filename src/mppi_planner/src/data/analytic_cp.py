def compute_collision_probabilities(d_nominal_array, d_collision=0, sigma=0.2):
    """
    Compute the probability of collision for an array of nominal distances.
    
    Parameters:
    - d_nominal_array: array-like, nominal distances (mean distances between centers)
    - d_collision: float, collision threshold (default: 0.625m)
    - sigma: float, standard deviation of uncertainty (default: 0.1m)
    
    Returns:
    - np.array of collision probabilities
    """
    z_scores = (d_collision - np.array(d_nominal_array)) / sigma
    return stats.norm.cdf(z_scores)

